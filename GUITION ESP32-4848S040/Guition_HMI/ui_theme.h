#define C_TEXT_MUTE     lv_color_hex(0x7C9389)   // จาง ๆ / ถูกล็อก (เข้มขึ้นให้ชัดบนพื้นมิ้น)

// สี accent -- เขียวมิ้น (สีหลักของธีมใหม่)
#define C_NEON          lv_color_hex(0x0FB89A)   // เขียวมิ้นเข้ม -- อ่านออกบนพื้นขาว
#define C_NEON_DIM      lv_color_hex(0x9AD7CC)   // มิ้นจาง (ท่อ/ของที่ยังไม่ทำงาน)

// สีโลโก้ FACTORYBOXX -- คงสีฟ้าแบรนด์ไว้ (รูปจริง ฟ้าบนขาวอ่านออกดี)
#define C_LOGO          lv_color_hex(0x1E88E5)

#define C_OK            lv_color_hex(0x15A34A)   // เขียวหญ้าเข้ม = ทำงาน/ปกติ (ต่างจากมิ้น accent)
#define C_WARN          lv_color_hex(0xD97706)   // ส้มอำพันเข้ม = เตือน
