// ---------------------------------------------------------------------------
//  สีประจำ "ชนิดของไหล" ในผัง P&ID หน้าหลัก
//
//  แยกสีตามสิ่งที่ไหลอยู่ในท่อ ไม่ใช่ตามอุปกรณ์ -- เป็นวิธีของ SCADA จริง
