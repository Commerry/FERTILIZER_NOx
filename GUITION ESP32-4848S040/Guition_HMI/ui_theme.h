#define C_PANEL_TOP     lv_color_hex(0xFFFFFF)   // การ์ดทั่วไป (ขาว -- เด่นบนพื้นเขียว)
#define C_PANEL_BOT     lv_color_hex(0xE9F5EF)

#define C_PANEL_HI_TOP  lv_color_hex(0xD0EEE1)   // การ์ด/แถวที่ถูกเน้นหรือถูกกด (มิ้นเข้ม)
#define C_PANEL_HI_BOT  lv_color_hex(0xAEDECB)

#define C_HEADER_TOP    lv_color_hex(0xD8F1E7)   // แถบหัว + แถบนำทาง (แถบมิ้น)
#define C_HEADER_BOT    lv_color_hex(0xBEE5D6)

// ร่อง (ราง bar/slider, ช่องพิมพ์): บนเข้ม-ล่างสว่าง = ดูจมลงไปบนพื้นสว่าง
#define C_SUNK_TOP      lv_color_hex(0xBAD8CC)
#define C_SUNK_BOT      lv_color_hex(0xE4F3EC)

#define C_LOG_TOP       lv_color_hex(0xD4E9E0)   // กล่อง log (console จม ๆ บนพื้นเขียว)
#define C_LOG_BOT       lv_color_hex(0xE9F5EF)

// ปุ่มสี: จากสีฐาน ให้สว่างขึ้นที่ขอบบน / เข้มลงที่ขอบล่าง (0-255)
// ธีมสว่าง -> ลดลงจากเดิมนิดหน่อย ไม่ให้ปุ่มสีอ่อนสว่างจนขอบหาย
