//
//  ธีมสว่าง: พื้นขาว/มิ้นอ่อน + ตัวอักษรเข้ม + accent เขียวมิ้น
//  *** ตัวอักษรต้องเข้มบนพื้นสว่าง *** (กลับจากธีมมืดเดิมที่ตัวอักษรสว่าง)
//  ปุ่มเลือกสีตัวอักษรเองตามความสว่างของปุ่ม (ดู text_on() ใน ui.cpp)
//  -> ปุ่มสีอ่อนได้ตัวอักษรเข้ม / ปุ่มสีเข้ม-สดได้ตัวอักษรขาว อัตโนมัติ
// ---------------------------------------------------------------------------
#define C_BG            lv_color_hex(0xD3EDE1)   // พื้นหลังรวม (มิ้นอ่อนชัด)
#define C_PANEL         lv_color_hex(0xFFFFFF)   // การ์ด / พาเนล (ขาว -- ลอยเด่นบนพื้นเขียว)
#define C_PANEL_HI      lv_color_hex(0xBBE5D4)   // พาเนลที่เน้น / ถูกเลือก (มิ้นเข้มขึ้น)
#define C_LINE          lv_color_hex(0xAAD0C0)   // เส้นขอบ / เส้นแบ่ง (เขียวมิ้น)
#define C_HEADER        lv_color_hex(0xCBEADD)   // แถบหัว (แถบมิ้น)

// ---------------------------------------------------------------------------
//  ไล่เฉดสี -- "ทุกกรอบ" ในระบบไล่จาก สว่างบน -> เข้มล่าง
//
//  ทำไมต้องทิศเดียวกันทั้งจอ:
//    สมองอ่านไล่เฉดเป็น "แสงมาจากด้านบน" กรอบเลยดูนูนขึ้นมาจริง ๆ
//    ถ้าสลับทิศมั่ว แต่ละกรอบจะดูเหมือนคนละแสง = หลุดกัน ไม่เป็นชิ้นเดียว
//    ทิศนี้ยังตรงกับรูปถัง (soil.png) ที่ไฟส่องจากบนพอดี
//
//  ข้อยกเว้นที่ "ตั้งใจ" กลับหัว (เข้มบน-สว่างล่าง) = ดูจมลงไป:
//    - ตอนกดปุ่ม   -> feedback ว่ากดโดนจริง
//    - ราง bar / slider / ช่องพิมพ์ / กล่อง log -> เป็นร่อง ไม่ใช่ของนูน
//
//  ค่าเฉลี่ยของแต่ละคู่ตั้งให้ใกล้สีเดิม -> โทนรวมไม่เปลี่ยน แค่มีมิติขึ้น
// ---------------------------------------------------------------------------
// พื้นจอ: ไล่เฉดชัด อ่อนด้านบน -> มิ้นเข้มด้านล่าง (แบบท้องฟ้า) ให้ดูมีมิติ
// ช่วงกว้างขึ้นกว่าเดิม -> เห็นเป็นไล่เฉดจริง ไม่ใช่แค่โทนเดียว
