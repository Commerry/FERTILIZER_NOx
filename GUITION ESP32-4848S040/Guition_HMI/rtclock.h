// ============================================================================
//  rtclock.h  --  นาฬิกาเวลาจริง (สำหรับประทับเวลาใน log)
//
//  ทั้ง Nano และ ESP32 ไม่มี RTC ในตัว -> ผู้ใช้ตั้งเวลาบนหน้าจอ
//  เก็บลง NVS (แฟลชภายใน ESP32) -> เปิดเครื่องใหม่ค่ากลับมาใกล้เคียง
//  แล้วเดินต่อด้วย millis()
//
//  ข้อจำกัดที่ยอมรับแล้ว: ปิดเครื่องนานเท่าไร นาฬิกาจะช้าไปเท่านั้น
//  (millis() หยุดตอนไฟดับ) -> ต้องตั้งใหม่หลังปิดเครื่องนาน ๆ
//
//  ต่อ DS3231 เพิ่มได้: เปิด RTCLOCK_USE_DS3231 -> ถ้าเจอโมดูลที่ I2C 0x68
//  จะใช้เป็นแหล่งเวลาหลักแทน (แม่นยำ + ไฟดับก็เดินต่อด้วยแบตของมันเอง)
// ============================================================================
#ifndef RTCLOCK_H
#define RTCLOCK_H

#include <Arduino.h>
#include <stdint.h>

// 0 = ใช้นาฬิกาตั้งเองอย่างเดียว (ค่าเริ่มต้น -- ไม่ต้องมีฮาร์ดแวร์เพิ่ม)
// 1 = ลองหา DS3231 ที่ I2C 0x68 ตอนบูต เจอแล้วใช้เป็นแหล่งเวลาหลัก
#define RTCLOCK_USE_DS3231   0

void     clock_begin();                 // โหลดค่าล่าสุดจาก NVS (+ หา DS3231 ถ้าเปิด)
void     clock_task();                  // เรียกเป็นระยะ -- เซฟลง NVS กันไฟดับ
uint32_t clock_now();                   // epoch วินาที (นับแบบ local ไม่มี timezone)
bool     clock_is_set();                // ผู้ใช้เคยตั้งเวลาแล้วหรือยัง

void     clock_set(uint32_t epoch);     // ตั้งเวลา (จากหน้าจอ)

// ประกอบ/แยกส่วนเวลา -- ใช้ทั้งตอนตั้งค่าและตอนแสดงผล
uint32_t clock_make(int year, int mon, int day, int hh, int mm, int ss);
void     clock_break(uint32_t epoch, int *year, int *mon, int *day,
                     int *hh, int *mm, int *ss);

// จัดรูปข้อความ (คืนความยาวที่เขียน)
void clock_str_datetime(char *buf, uint32_t epoch);   // "2026-07-15 14:32:01"  (>=20 ไบต์)
void clock_str_date(char *buf, uint32_t epoch);        // "20260715"             (>=9 ไบต์)
void clock_str_clock(char *buf, uint32_t epoch);       // "14:32"                (>=6 ไบต์)

#endif // RTCLOCK_H
